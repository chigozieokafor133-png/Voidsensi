/* VOID'S SENSI'S — Node/Express API client */
(function () {
  'use strict';
  const api = {
    async request(path, options) {
      const response = await fetch(path, options);
      const data = await response.json().catch(() => ({}));
      if (!response.ok) throw new Error(data.error || `Request failed (${response.status})`);
      return data;
    },
    health: () => api.request('/api/health'),
    brands: () => api.request('/api/brands'),
    phones: (brand, q) => api.request(`/api/phones?brand=${encodeURIComponent(brand || '')}&q=${encodeURIComponent(q || '')}`),
    profile: params => api.request(`/api/sensitivity-profiles?${new URLSearchParams(params)}`),
    tools: () => api.request('/api/tools'),
    themes: () => api.request('/api/themes')
  };
  window.voidsApi = api;

  function ready(fn) { if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fn); else fn(); }
  ready(async function () {
    document.documentElement.dataset.voidApi = 'checking';
    try {
      const health = await api.health();
      document.documentElement.dataset.voidApi = 'online';
      const badge = document.querySelector('[data-void-api-status]');
      if (badge) badge.textContent = `● API ONLINE · v${health.version}`;
    } catch (error) {
      document.documentElement.dataset.voidApi = 'offline';
      const badge = document.querySelector('[data-void-api-status]');
      if (badge) badge.textContent = '● OFFLINE MODE';
    }

    const brandSelect = document.getElementById('brandSelect');
    const modelSelect = document.getElementById('modelSelect');
    if (brandSelect && modelSelect) {
      try {
        const data = await api.brands();
        const current = brandSelect.value;
        brandSelect.innerHTML = '<option value="">Select a brand</option>' + data.brands.map(b => `<option value="${b.replace(/"/g, '&quot;')}">${b}</option>`).join('');
        if (data.brands.includes(current)) brandSelect.value = current;

        async function loadModels() {
          const brand = brandSelect.value;
          const data = await api.phones(brand, '');
          modelSelect.innerHTML = '<option value="">Select a model</option>' + data.models.map(x => `<option value="${x.model.replace(/"/g, '&quot;')}">${x.model}</option>`).join('');
        }
        brandSelect.addEventListener('change', () => loadModels().catch(() => {}));
        await loadModels();
      } catch (_) {
        // The original page data remains available as a fallback.
      }
    }

    const generate = document.getElementById('generateBtn');
    if (generate && window.voidsApi && document.getElementById('generalVal')) {
      generate.addEventListener('click', async function () {
        const brand = document.getElementById('brandSelect')?.value || '';
        const selectModel = document.getElementById('modelSelect')?.value || '';
        const customModel = document.getElementById('customModel')?.value.trim() || '';
        const model = customModel || selectModel || 'Default model';
        const ram = document.getElementById('ramSelect')?.value || 4;
        const active = document.querySelector('.chip.active');
        const style = active?.dataset.style || 'Balanced';
        try {
          const data = await api.profile({ brand, model, ram, style });
          const ids = { General: 'generalVal', 'Red Dot': 'redVal', '2x Scope': 'twoVal', '4x Scope': 'fourVal', Sniper: 'sniperVal', 'Free Look': 'freeVal' };
          Object.entries(ids).forEach(([key, id]) => { if (data.profile[key] != null) document.getElementById(id).textContent = data.profile[key]; });
          const title = document.getElementById('resultTitle');
          const hint = document.getElementById('resultHint');
          if (title) title.textContent = `YOUR ${style.toUpperCase()} SETUP`;
          if (hint) hint.textContent = `For ${model} · ${ram} GB RAM · ${style} · generated by VOID'S SENSI'S API.`;
        } catch (_) {}
      });
    }
  });
})();
